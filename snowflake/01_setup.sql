-- AtlasLake on Snowflake (Phase 21) — run as ACCOUNTADMIN (or SYSADMIN + SECURITYADMIN split as noted).
-- Idempotent: safe to re-run.

USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS ATLASLAKE COMMENT = 'AtlasLake analytical serving warehouse';
CREATE SCHEMA IF NOT EXISTS ATLASLAKE.STAGING WITH MANAGED ACCESS COMMENT = 'Landing area for Gold loads (PUT/COPY)';
CREATE SCHEMA IF NOT EXISTS ATLASLAKE.GOLD    WITH MANAGED ACCESS COMMENT = 'Star schema + marts mirrored from dbt Gold';

CREATE WAREHOUSE IF NOT EXISTS ATLAS_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800
  COMMENT = 'AtlasLake loads + analytics (XS; scale only when a benchmark justifies it)';

-- Hard spend cap for the project account.
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS ATLAS_MONTHLY
  WITH CREDIT_QUOTA = 20 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE ATLAS_WH SET RESOURCE_MONITOR = ATLAS_MONTHLY;

-- ---------------------------------------------------------------- roles (SECURITYADMIN)
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS ATLAS_LOADER      COMMENT = 'Pipeline service role: loads STAGING, merges into GOLD';
CREATE ROLE IF NOT EXISTS ATLAS_TRANSFORMER COMMENT = 'dbt / engineers: owns GOLD objects';
CREATE ROLE IF NOT EXISTS ATLAS_ANALYST     COMMENT = 'Read-only analytics; PII masked';
CREATE ROLE IF NOT EXISTS ATLAS_PII_READER  COMMENT = 'May see unmasked PII-tagged columns (granted sparingly)';

-- hierarchy: analyst < pii_reader ; analyst < loader/transformer ; all roll up to SYSADMIN
GRANT ROLE ATLAS_ANALYST     TO ROLE ATLAS_PII_READER;
GRANT ROLE ATLAS_ANALYST     TO ROLE ATLAS_TRANSFORMER;
GRANT ROLE ATLAS_ANALYST     TO ROLE ATLAS_LOADER;
GRANT ROLE ATLAS_TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE ATLAS_LOADER      TO ROLE SYSADMIN;
GRANT ROLE ATLAS_PII_READER  TO ROLE SYSADMIN;

-- warehouse
GRANT USAGE, OPERATE ON WAREHOUSE ATLAS_WH TO ROLE ATLAS_LOADER;
GRANT USAGE, OPERATE ON WAREHOUSE ATLAS_WH TO ROLE ATLAS_TRANSFORMER;
GRANT USAGE          ON WAREHOUSE ATLAS_WH TO ROLE ATLAS_ANALYST;

-- database / schemas
GRANT USAGE ON DATABASE ATLASLAKE TO ROLE ATLAS_ANALYST;
GRANT USAGE ON SCHEMA ATLASLAKE.GOLD    TO ROLE ATLAS_ANALYST;
GRANT USAGE ON SCHEMA ATLASLAKE.STAGING TO ROLE ATLAS_LOADER;

GRANT CREATE TABLE, CREATE VIEW ON SCHEMA ATLASLAKE.GOLD TO ROLE ATLAS_TRANSFORMER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA ATLASLAKE.STAGING TO ROLE ATLAS_LOADER;

-- current + future object grants (managed-access schemas: grants are centrally controlled here)
GRANT SELECT ON ALL TABLES    IN SCHEMA ATLASLAKE.GOLD TO ROLE ATLAS_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ATLASLAKE.GOLD TO ROLE ATLAS_ANALYST;
GRANT SELECT ON ALL VIEWS     IN SCHEMA ATLASLAKE.GOLD TO ROLE ATLAS_ANALYST;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ATLASLAKE.GOLD TO ROLE ATLAS_ANALYST;

GRANT INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA ATLASLAKE.GOLD TO ROLE ATLAS_LOADER;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA ATLASLAKE.GOLD TO ROLE ATLAS_LOADER;
GRANT ALL ON FUTURE TABLES IN SCHEMA ATLASLAKE.STAGING TO ROLE ATLAS_LOADER;

-- service user for the publish step (key-pair auth; no password). Paste the public key:
CREATE USER IF NOT EXISTS ATLAS_LOADER_SVC
  DEFAULT_ROLE = ATLAS_LOADER
  DEFAULT_WAREHOUSE = ATLAS_WH
  DEFAULT_NAMESPACE = ATLASLAKE.GOLD
  TYPE = SERVICE
  COMMENT = 'AtlasLake publish job';
-- ALTER USER ATLAS_LOADER_SVC SET RSA_PUBLIC_KEY = '<contents of rsa_key.pub>';
GRANT ROLE ATLAS_LOADER TO USER ATLAS_LOADER_SVC;

-- file format + internal stage used by `atlas publish --target snowflake`
USE ROLE ATLAS_LOADER;
USE SCHEMA ATLASLAKE.STAGING;
CREATE FILE FORMAT IF NOT EXISTS PARQUET_FMT TYPE = PARQUET USE_LOGICAL_TYPE = TRUE;
CREATE STAGE IF NOT EXISTS GOLD_STAGE FILE_FORMAT = PARQUET_FMT COMMENT = 'Parquet exports of dbt Gold';
